	FMOVS (R16), F8
	B weights
left_load:
	VEOR V8.B16, V8.B16, V8.B16
	MOVD R16, R13
	CMP $2, R26
	BEQ left_two
	BGT left_three
	VLD1.P 4(R13), V8.S[1]
	CMP $2, R14
	BEQ weights
left_two:
	VLD1.P 4(R13), V8.S[2]
	CMP $3, R14
	BEQ weights
left_three:
