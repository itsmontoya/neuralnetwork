	VDUP R26, V25.S4
	VDUP R14, V26.S4
	VCMGE V25.S4, V31.S4, V25.S4
	VCMGT V31.S4, V26.S4, V26.S4
	VAND V26.B16, V25.B16, V25.B16
	VMOV V0.B16, V17.B16
	VMOV V1.B16, V18.B16
