	LSL $2, R5, R22
	VEOR V0.B16, V0.B16, V0.B16
	VEOR V1.B16, V1.B16, V1.B16
	VEOR V2.B16, V2.B16, V2.B16
	VEOR V3.B16, V3.B16, V3.B16
	VEOR V4.B16, V4.B16, V4.B16
	VEOR V5.B16, V5.B16, V5.B16
	VEOR V6.B16, V6.B16, V6.B16
	VEOR V7.B16, V7.B16, V7.B16

channel_loop:
	MOVD R0, R10
	MOVD R1, R11
	MOVD R4, R12
row_loop:
	MOVD R10, R16
	MOVD R11, R17
	ADD R9, R17, R19
	ADD R9, R19, R20
	ADD R9, R20, R21
	MOVD R5, R15
column_loop:
	VLD1 (R16), [V8.S4]
	ADD $4, R16, R16
	ADD R9<<2, R17, R13
	VLD1R (R13), [V13.S4]
	ADD R9<<2, R19, R13
	VLD1R (R13), [V14.S4]
	ADD R9<<2, R20, R13
	VLD1R (R13), [V15.S4]
	ADD R9<<2, R21, R13
	VLD1R (R13), [V16.S4]
	VLD1R.P 4(R17), [V9.S4]
	VLD1R.P 4(R19), [V10.S4]
	VLD1R.P 4(R20), [V11.S4]
	VLD1R.P 4(R21), [V12.S4]
	// Match the scalar spatial helper's weight-first NaN operand priority.
	VFMLA V8.S4, V9.S4, V0.S4
	VFMLA V8.S4, V10.S4, V1.S4
	VFMLA V8.S4, V11.S4, V2.S4
	VFMLA V8.S4, V12.S4, V3.S4
	VFMLA V8.S4, V13.S4, V4.S4
	VFMLA V8.S4, V14.S4, V5.S4
	VFMLA V8.S4, V15.S4, V6.S4
	VFMLA V8.S4, V16.S4, V7.S4
	SUBS $1, R15, R15
	BNE column_loop
	ADD R7, R10, R10
	ADD R22, R11, R11
	SUBS $1, R12, R12
	BNE row_loop
	ADD R6, R0, R0
	ADD R8, R1, R1
	SUBS $1, R3, R3
	BNE channel_loop
	MOVD bias_base+72(FP), R1
	MOVD bias_len+80(FP), R3
	CBZ R3, store
	VLD1R.P 4(R1), [V9.S4]
	VFADD V9.S4, V0.S4, V0.S4
	VLD1R.P 4(R1), [V9.S4]
	VFADD V9.S4, V1.S4, V1.S4
	VLD1R.P 4(R1), [V9.S4]
	VFADD V9.S4, V2.S4, V2.S4
	VLD1R.P 4(R1), [V9.S4]
	VFADD V9.S4, V3.S4, V3.S4
	VLD1R.P 4(R1), [V9.S4]
	VFADD V9.S4, V4.S4, V4.S4
	VLD1R.P 4(R1), [V9.S4]
	VFADD V9.S4, V5.S4, V5.S4
	VLD1R.P 4(R1), [V9.S4]
	VFADD V9.S4, V6.S4, V6.S4
	VLD1R.P 4(R1), [V9.S4]
	VFADD V9.S4, V7.S4, V7.S4
store:
	MOVD plane+144(FP), R3
	LSL $2, R3, R3
	VST1 [V0.S4], (R2)
	ADD R3, R2, R2
	VST1 [V1.S4], (R2)
	ADD R3, R2, R2
	VST1 [V2.S4], (R2)
	ADD R3, R2, R2
	VST1 [V3.S4], (R2)
	ADD R3, R2, R2
	VST1 [V4.S4], (R2)
	ADD R3, R2, R2
	VST1 [V5.S4], (R2)
	ADD R3, R2, R2
	VST1 [V6.S4], (R2)
	ADD R3, R2, R2
	VST1 [V7.S4], (R2)
	RET

