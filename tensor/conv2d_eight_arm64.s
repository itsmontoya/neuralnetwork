	MOVD $0x0000000100000000, R13
	VMOV R13, V31.D[0]
	MOVD $0x0000000300000002, R13
	VMOV R13, V31.D[1]

channel_loop:
	MOVD R0, R10
	MOVD R1, R11
	MOVD R4, R12
