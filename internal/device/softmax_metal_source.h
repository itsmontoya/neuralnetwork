static const char *nnMetalTensorSoftmaxSource =
	"kernel void nn_tensor_softmax_last_axis(\n"
	"    const device float *input [[buffer(0)]],\n"
	"    device float *result [[buffer(1)]],\n"
	"    constant uint *params [[buffer(2)]],\n"
	"    uint row [[threadgroup_position_in_grid]],\n"
	"    uint tid [[thread_index_in_threadgroup]],\n"
	"    uint tgSize [[threads_per_threadgroup]],\n"
	"    uint simdGroup [[simdgroup_index_in_threadgroup]],\n"
	"    uint simdLane [[thread_index_in_simdgroup]],\n"
	"    uint numSimdGroups [[simdgroups_per_threadgroup]]\n"
	") {\n"
	"    threadgroup float shared[34];\n"
	"    uint axisSize = params[0];\n"
	"    ulong start = ulong(row) * ulong(axisSize);\n"
	"    float localMax = -INFINITY;\n"
	"    if ((axisSize & 3u) == 0u) {\n"
	"        uint vecWidth = axisSize >> 2;\n"
	"        const device float4 *in4 = (const device float4 *)(input + start);\n"
	"        for (uint i = tid; i < vecWidth; i += tgSize) {\n"
	"            float4 v = in4[i];\n"
	"            localMax = max(localMax, max(max(v.x, v.y), max(v.z, v.w)));\n"
	"        }\n"
	"    } else {\n"
	"        for (uint i = tid; i < axisSize; i += tgSize) {\n"
	"            localMax = max(localMax, input[start + i]);\n"
	"        }\n"
	"    }\n"
	"    localMax = simd_max(localMax);\n"
	"    if (simdLane == 0) {\n"
	"        shared[simdGroup] = localMax;\n"
	"    }\n"
	"    threadgroup_barrier(mem_flags::mem_threadgroup);\n"
	"    if (simdGroup == 0) {\n"
	"        float m = (simdLane < numSimdGroups) ? shared[simdLane] : -INFINITY;\n"
	"        m = simd_max(m);\n"
	"        if (simdLane == 0) {\n"
	"            shared[32] = m;\n"
	"        }\n"
	"    }\n"
	"    threadgroup_barrier(mem_flags::mem_threadgroup);\n"
	"    float rowMax = shared[32];\n"
	"    float localSum = 0.0f;\n"
	"    if ((axisSize & 3u) == 0u) {\n"
	"        uint vecWidth = axisSize >> 2;\n"
	"        const device float4 *in4 = (const device float4 *)(input + start);\n"
	"        device float4 *out4 = (device float4 *)(result + start);\n"
	"        for (uint i = tid; i < vecWidth; i += tgSize) {\n"
	"            float4 e = exp(in4[i] - rowMax);\n"
	"            out4[i] = e;\n"
	"            localSum += (e.x + e.y) + (e.z + e.w);\n"
	"        }\n"
	"    } else {\n"
	"        for (uint i = tid; i < axisSize; i += tgSize) {\n"
	"            float e = exp(input[start + i] - rowMax);\n"
	"            result[start + i] = e;\n"
	"            localSum += e;\n"
	"        }\n"
	"    }\n"
	"    localSum = simd_sum(localSum);\n"
	"    if (simdLane == 0) {\n"
	"        shared[simdGroup] = localSum;\n"
	"    }\n"
	"    threadgroup_barrier(mem_flags::mem_threadgroup);\n"
	"    if (simdGroup == 0) {\n"
	"        float s = (simdLane < numSimdGroups) ? shared[simdLane] : 0.0f;\n"
	"        s = simd_sum(s);\n"
	"        if (simdLane == 0) {\n"
	"            shared[33] = s;\n"
	"        }\n"
	"    }\n"
	"    threadgroup_barrier(mem_flags::mem_threadgroup);\n"
	"    float rowSum = shared[33];\n"
	"    if ((axisSize & 3u) == 0u) {\n"
	"        uint vecWidth = axisSize >> 2;\n"
	"        device float4 *out4 = (device float4 *)(result + start);\n"
	"        for (uint i = tid; i < vecWidth; i += tgSize) {\n"
	"            out4[i] = out4[i] / rowSum;\n"
	"        }\n"
	"    } else {\n"
	"        for (uint i = tid; i < axisSize; i += tgSize) {\n"
	"            result[start + i] = result[start + i] / rowSum;\n"
	"        }\n"
	"    }\n"
	"}\n"
	"kernel void nn_tensor_softmax_strided(\n"
	"    const device float *input [[buffer(0)]],\n"
	"    device float *result [[buffer(1)]],\n"
	"    constant uint *params [[buffer(2)]],\n"
	"    uint slice [[thread_position_in_grid]]\n"
	") {\n"
	"    uint outer = params[0];\n"
	"    uint axisSize = params[1];\n"
	"    uint inner = params[2];\n"
	"    ulong totalSlices = ulong(outer) * ulong(inner);\n"
	"    if (ulong(slice) >= totalSlices) {\n"
	"        return;\n"
	"    }\n"
	"    uint o = slice / inner;\n"
	"    uint inIdx = slice % inner;\n"
	"    ulong base = (ulong(o) * ulong(axisSize)) * ulong(inner) + ulong(inIdx);\n"
	"    ulong stride = ulong(inner);\n"
	"    float rowMax = -INFINITY;\n"
	"    for (uint a = 0; a < axisSize; a++) {\n"
	"        rowMax = max(rowMax, input[base + ulong(a) * stride]);\n"
	"    }\n"
	"    float rowSum = 0.0f;\n"
	"    for (uint a = 0; a < axisSize; a++) {\n"
	"        float e = exp(input[base + ulong(a) * stride] - rowMax);\n"
	"        result[base + ulong(a) * stride] = e;\n"
	"        rowSum += e;\n"
	"    }\n"
	"    for (uint a = 0; a < axisSize; a++) {\n"
	"        result[base + ulong(a) * stride] = result[base + ulong(a) * stride] / rowSum;\n"
	"    }\n"
	"}\n";

