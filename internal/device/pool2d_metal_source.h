#ifndef NN_INTERNAL_DEVICE_POOL2D_METAL_SOURCE_H
#define NN_INTERNAL_DEVICE_POOL2D_METAL_SOURCE_H

static const char *nnMetalTensorPool2DSource =
	"struct NNPool2DParams {\n"
	"    uint channelsTotal;\n"
	"    uint inH;\n"
	"    uint inW;\n"
	"    uint outH;\n"
	"    uint outW;\n"
	"    uint kernelH;\n"
	"    uint kernelW;\n"
	"    uint strideH;\n"
	"    uint strideW;\n"
	"    uint padTop;\n"
	"    uint padLeft;\n"
	"    uint dilationH;\n"
	"    uint dilationW;\n"
	"    uint countIncludePad;\n"
	"};\n"
	"kernel void nn_tensor_max_pool2d(\n"
	"    const device float *input [[buffer(0)]],\n"
	"    device float *result [[buffer(1)]],\n"
	"    constant NNPool2DParams &params [[buffer(2)]],\n"
	"    uint3 gid [[thread_position_in_grid]]\n"
	") {\n"
	"    uint ow = gid.x;\n"
	"    uint oh = gid.y;\n"
	"    uint nc = gid.z;\n"
	"    int inH = int(params.inH);\n"
	"    int inW = int(params.inW);\n"
	"    int startH = int(oh) * int(params.strideH) - int(params.padTop);\n"
	"    int startW = int(ow) * int(params.strideW) - int(params.padLeft);\n"
	"    int dilH = int(params.dilationH);\n"
	"    int dilW = int(params.dilationW);\n"
	"    int kH = int(params.kernelH);\n"
	"    int kW = int(params.kernelW);\n"
	"    int firstH = 0;\n"
	"    if (startH < 0) {\n"
	"        firstH = (-startH + dilH - 1) / dilH;\n"
	"    }\n"
	"    int endH = 0;\n"
	"    if (startH < inH) {\n"
	"        int limH = (inH - 1 - startH) / dilH + 1;\n"
	"        endH = (limH < kH) ? limH : kH;\n"
	"    }\n"
	"    int firstW = 0;\n"
	"    if (startW < 0) {\n"
	"        firstW = (-startW + dilW - 1) / dilW;\n"
	"    }\n"
	"    int endW = 0;\n"
	"    if (startW < inW) {\n"
	"        int limW = (inW - 1 - startW) / dilW + 1;\n"
	"        endW = (limW < kW) ? limW : kW;\n"
	"    }\n"
	"    uint inBase = nc * params.inH * params.inW;\n"
	"    float best = -INFINITY;\n"
	"    for (int kh = firstH; kh < endH; kh++) {\n"
	"        uint rowBase = inBase + uint(startH + kh * dilH) * params.inW;\n"
	"        for (int kw = firstW; kw < endW; kw++) {\n"
	"            float sample = input[rowBase + uint(startW + kw * dilW)];\n"
	"            if (sample > best || isnan(sample)) {\n"
	"                best = sample;\n"
	"            }\n"
	"        }\n"
	"    }\n"
	"    uint outOffset = (nc * params.outH + oh) * params.outW + ow;\n"
	"    result[outOffset] = best;\n"
	"}\n"
	"kernel void nn_tensor_avg_pool2d(\n"
	"    const device float *input [[buffer(0)]],\n"
	"    device float *result [[buffer(1)]],\n"
	"    constant NNPool2DParams &params [[buffer(2)]],\n"
	"    uint3 gid [[thread_position_in_grid]]\n"
	") {\n"
	"    uint ow = gid.x;\n"
	"    uint oh = gid.y;\n"
	"    uint nc = gid.z;\n"
	"    int inH = int(params.inH);\n"
	"    int inW = int(params.inW);\n"
	"    int startH = int(oh) * int(params.strideH) - int(params.padTop);\n"
	"    int startW = int(ow) * int(params.strideW) - int(params.padLeft);\n"
	"    int dilH = int(params.dilationH);\n"
	"    int dilW = int(params.dilationW);\n"
	"    int kH = int(params.kernelH);\n"
	"    int kW = int(params.kernelW);\n"
	"    int firstH = 0;\n"
	"    if (startH < 0) {\n"
	"        firstH = (-startH + dilH - 1) / dilH;\n"
	"    }\n"
	"    int endH = 0;\n"
	"    if (startH < inH) {\n"
	"        int limH = (inH - 1 - startH) / dilH + 1;\n"
	"        endH = (limH < kH) ? limH : kH;\n"
	"    }\n"
	"    int firstW = 0;\n"
	"    if (startW < 0) {\n"
	"        firstW = (-startW + dilW - 1) / dilW;\n"
	"    }\n"
	"    int endW = 0;\n"
	"    if (startW < inW) {\n"
	"        int limW = (inW - 1 - startW) / dilW + 1;\n"
	"        endW = (limW < kW) ? limW : kW;\n"
	"    }\n"
	"    uint inBase = nc * params.inH * params.inW;\n"
	"    float sum = 0.0f;\n"
	"    for (int kh = firstH; kh < endH; kh++) {\n"
	"        uint rowBase = inBase + uint(startH + kh * dilH) * params.inW;\n"
	"        for (int kw = firstW; kw < endW; kw++) {\n"
	"            sum += input[rowBase + uint(startW + kw * dilW)];\n"
	"        }\n"
	"    }\n"
	"    float divisor;\n"
	"    if (params.countIncludePad != 0u) {\n"
	"        divisor = float(params.kernelH) * float(params.kernelW);\n"
	"    } else {\n"
	"        int rows = (endH > firstH) ? (endH - firstH) : 0;\n"
	"        int cols = (endW > firstW) ? (endW - firstW) : 0;\n"
	"        divisor = float(uint(rows) * uint(cols));\n"
	"    }\n"
	"    uint outOffset = (nc * params.outH + oh) * params.outW + ow;\n"
	"    result[outOffset] = sum / divisor;\n"
	"}\n";

#endif
