	"kernel void nn_tensor_rms_norm(\n"
	"    const device float *input [[buffer(0)]],\n"
	"    const device float *weight [[buffer(1)]],\n"
	"    device float *result [[buffer(2)]],\n"
	"    constant uint *params [[buffer(4)]],\n"
	"    uint row [[thread_position_in_grid]]\n"
	") {\n"
	"    uint width = params[0];\n"
	"    uint start = row * width;\n"
	"    float rootEpsilon = as_type<float>(params[1]);\n"
	"    float scale = rootEpsilon;\n"
	"    for (uint feature = 0; feature < width; feature++) {\n"
	"        scale = max(scale, fabs(input[start + feature]));\n"
	"    }\n"
	"    float sum = 0.0f;\n"
	"    for (uint feature = 0; feature < width; feature++) {\n"
	"        float x = input[start + feature] / scale;\n"
	"        sum += x * x;\n"
	"    }\n"
	"    float scaledEpsilon = rootEpsilon / scale;\n"
	"    float inverse = rsqrt(sum / float(width) + scaledEpsilon * scaledEpsilon);\n"
	"    for (uint feature = 0; feature < width; feature++) {\n"
	"        result[start + feature] = ((input[start + feature] / scale) * inverse) * weight[feature];\n"
	"    }\n"
	"}\n"
	"kernel void nn_tensor_rotate_pairs(\n"
	"    const device float *input [[buffer(0)]],\n"
	"    const device float *cosine [[buffer(1)]],\n"
	"    device float *result [[buffer(2)]],\n"
	"    const device float *sine [[buffer(3)]],\n"
	"    constant uint *params [[buffer(4)]],\n"
	"    uint pair [[thread_position_in_grid]]\n"
	") {\n"
	"    uint pairs = params[0];\n"
	"    uint row = pair / (pairs * params[1]);\n"
	"    uint coefficient = (params[2] + row) * pairs + pair % pairs;\n"
	"    float c = cosine[coefficient];\n"
	"    float s = sine[coefficient];\n"
	"    float first = input[2 * pair];\n"
	"    float second = input[2 * pair + 1];\n"
	"    result[2 * pair] = first * c - second * s;\n"
	"    result[2 * pair + 1] = second * c + first * s;\n"
	"}\n"
	"kernel void nn_tensor_causal_attention(\n"
	"    const device float *queries [[buffer(0)]],\n"
	"    const device float *history [[buffer(1)]],\n"
	"    device float *result [[buffer(2)]],\n"
	"    constant uint *params [[buffer(4)]],\n"
	"    uint index [[thread_position_in_grid]]\n"
	") {\n"
	"    uint width = params[0];\n"
	"    uint heads = params[1];\n"
	"    uint kvHeads = params[2];\n"
	"    uint plane = params[3];\n"
	"    uint length = params[4];\n"
	"    uint visible = min(length, params[5] + min(length, index / heads) + 1);\n"
	"    uint kvHead = (index % heads) / (heads / kvHeads);\n"
	"    uint start = index * width;\n"
	"    float scale = rsqrt(float(width));\n"
	"    float maximum = -INFINITY;\n"
	"    float total = 0.0f;\n"
	"    for (uint feature = 0; feature < width; feature++) {\n"
	"        result[start + feature] = 0.0f;\n"
	"    }\n"
	"    for (uint row = 0; row < visible; row++) {\n"
	"        uint offset = (row * kvHeads + kvHead) * width;\n"
	"        float dot = 0.0f;\n"
	"        for (uint feature = 0; feature < width; feature++) {\n"
	"            dot += queries[start + feature] * history[offset + feature];\n"
	"        }\n"
	"        float score = dot * scale;\n"
	"        float nextMaximum = max(maximum, score);\n"
	"        // Shift the old denominator and the new term to the same maximum.\n"
	"        float keep = total * exp(maximum - nextMaximum);\n"
	"        float add = exp(score - nextMaximum);\n"
	"        total = keep + add;\n"
	"        maximum = nextMaximum;\n"
	"        keep /= total;\n"
	"        add /= total;\n"
	"        for (uint feature = 0; feature < width; feature++) {\n"
	"            result[start + feature] = keep * result[start + feature] + add * history[plane + offset + feature];\n"
	"        }\n"
	"    }\n"
	"}\n";

