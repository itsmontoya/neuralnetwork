#ifndef NN_INTERNAL_DEVICE_LAYERNORM_METAL_SOURCE_H
#define NN_INTERNAL_DEVICE_LAYERNORM_METAL_SOURCE_H

static const char *nnMetalTensorLayerNormSource =
	"static inline float nn_layernorm_load(const device void *buf, uint idx, uint dtype) {\n"
	"    if (dtype == 1u) {\n"
	"        return float(((const device half *)buf)[idx]);\n"
	"    }\n"
	"    if (dtype == 2u) {\n"
	"        return float(((const device bfloat *)buf)[idx]);\n"
	"    }\n"
	"    return ((const device float *)buf)[idx];\n"
	"}\n"
	"static inline float4 nn_layernorm_load4(const device void *buf, uint idx, uint dtype) {\n"
	"    if (dtype == 1u) {\n"
	"        return float4(((const device half4 *)buf)[idx]);\n"
	"    }\n"
	"    if (dtype == 2u) {\n"
	"        return float4(((const device bfloat4 *)buf)[idx]);\n"
	"    }\n"
	"    return ((const device float4 *)buf)[idx];\n"
	"}\n"
	"kernel void nn_tensor_layer_norm(\n"
	"    const device float *input [[buffer(0)]],\n"
	"    const device void *weight [[buffer(1)]],\n"
	"    const device void *bias [[buffer(2)]],\n"
	"    device float *result [[buffer(3)]],\n"
	"    constant uint *params [[buffer(4)]],\n"
	"    uint row [[threadgroup_position_in_grid]],\n"
	"    uint tid [[thread_index_in_threadgroup]],\n"
	"    uint tgSize [[threads_per_threadgroup]],\n"
	"    uint simdGroup [[simdgroup_index_in_threadgroup]],\n"
	"    uint simdLane [[thread_index_in_simdgroup]],\n"
	"    uint numSimdGroups [[simdgroups_per_threadgroup]]\n"
	") {\n"
	"    threadgroup float shared[34];\n"
	"    uint width = params[0];\n"
	"    float epsilon = as_type<float>(params[1]);\n"
	"    uint weightDType = params[2];\n"
	"    uint biasDType = params[3];\n"
	"    uint hasBias = params[4];\n"
	"    ulong start = ulong(row) * ulong(width);\n"
	"    float x0 = input[start];\n"
	"    bool vec = (width & 3u) == 0u;\n"
	"    uint vecWidth = width >> 2;\n"
	"    float localSum = 0.0f;\n"
	"    if (vec) {\n"
	"        const device float4 *in4 = (const device float4 *)(input + start);\n"
	"        for (uint i = tid; i < vecWidth; i += tgSize) {\n"
	"            float4 v = in4[i] - x0;\n"
	"            localSum += (v.x + v.y) + (v.z + v.w);\n"
	"        }\n"
	"    } else {\n"
	"        for (uint i = tid; i < width; i += tgSize) {\n"
	"            localSum += input[start + i] - x0;\n"
	"        }\n"
	"    }\n"
	"    localSum = simd_sum(localSum);\n"
	"    if (simdLane == 0) {\n"
	"        shared[simdGroup] = localSum;\n"
	"    }\n"
	"    threadgroup_barrier(mem_flags::mem_threadgroup);\n"
	"    if (simdGroup == 0) {\n"
	"        float s = (simdLane < numSimdGroups) ? shared[simdLane] : 0.0f;\n"
	"        s = simd_sum(s);\n"
	"        if (simdLane == 0) {\n"
	"            shared[32] = s / float(width);\n"
	"        }\n"
	"    }\n"
	"    threadgroup_barrier(mem_flags::mem_threadgroup);\n"
	"    float shiftedMean = shared[32];\n"
	"    float localVar = 0.0f;\n"
	"    if (vec) {\n"
	"        const device float4 *in4 = (const device float4 *)(input + start);\n"
	"        for (uint i = tid; i < vecWidth; i += tgSize) {\n"
	"            float4 d = (in4[i] - x0) - shiftedMean;\n"
	"            localVar += (d.x * d.x + d.y * d.y) + (d.z * d.z + d.w * d.w);\n"
	"        }\n"
	"    } else {\n"
	"        for (uint i = tid; i < width; i += tgSize) {\n"
	"            float d = (input[start + i] - x0) - shiftedMean;\n"
	"            localVar += d * d;\n"
	"        }\n"
	"    }\n"
	"    localVar = simd_sum(localVar);\n"
	"    if (simdLane == 0) {\n"
	"        shared[simdGroup] = localVar;\n"
	"    }\n"
	"    threadgroup_barrier(mem_flags::mem_threadgroup);\n"
	"    if (simdGroup == 0) {\n"
	"        float s = (simdLane < numSimdGroups) ? shared[simdLane] : 0.0f;\n"
	"        s = simd_sum(s);\n"
	"        if (simdLane == 0) {\n"
	"            float var = s / float(width);\n"
	"            shared[33] = 1.0f / sqrt(var + epsilon);\n"
	"        }\n"
	"    }\n"
	"    threadgroup_barrier(mem_flags::mem_threadgroup);\n"
	"    float invStd = shared[33];\n"
	"    if (vec) {\n"
	"        const device float4 *in4 = (const device float4 *)(input + start);\n"
	"        device float4 *out4 = (device float4 *)(result + start);\n"
	"        for (uint i = tid; i < vecWidth; i += tgSize) {\n"
	"            float4 norm = ((in4[i] - x0) - shiftedMean) * invStd;\n"
	"            float4 out = norm * nn_layernorm_load4(weight, i, weightDType);\n"
	"            if (hasBias != 0u) {\n"
	"                out += nn_layernorm_load4(bias, i, biasDType);\n"
	"            }\n"
	"            out4[i] = out;\n"
	"        }\n"
	"    } else {\n"
	"        for (uint i = tid; i < width; i += tgSize) {\n"
	"            float norm = ((input[start + i] - x0) - shiftedMean) * invStd;\n"
	"            float out = norm * nn_layernorm_load(weight, i, weightDType);\n"
	"            if (hasBias != 0u) {\n"
	"                out += nn_layernorm_load(bias, i, biasDType);\n"
	"            }\n"
	"            result[start + i] = out;\n"
	"        }\n"
	"    }\n"
	"}\n";

#endif
