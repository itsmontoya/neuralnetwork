#ifndef NN_INTERNAL_DEVICE_BROADCAST_METAL_SOURCE_H
#define NN_INTERNAL_DEVICE_BROADCAST_METAL_SOURCE_H

static const char *nnMetalTensorBroadcastSource =
	"struct NNMetalBroadcastParams {\n"
	"    uint op;\n"
	"    uint rank;\n"
	"    uint count;\n"
	"    uint mode;\n"
	"    uint dims[6];\n"
	"    uint outStrides[6];\n"
	"    uint leftStrides[6];\n"
	"    uint rightStrides[6];\n"
	"};\n"
	"static float nn_broadcast_apply(uint op, float a, float b) {\n"
	"    switch (op) {\n"
	"    case 0u:\n"
	"        return a + b;\n"
	"    case 1u:\n"
	"        return a - b;\n"
	"    case 2u:\n"
	"        return a * b;\n"
	"    default:\n"
	"        return a / b;\n"
	"    }\n"
	"}\n"
	"kernel void nn_tensor_scale(\n"
	"    const device float *input [[buffer(0)]],\n"
	"    device float *result [[buffer(1)]],\n"
	"    constant float &scale [[buffer(2)]],\n"
	"    uint index [[thread_position_in_grid]]\n"
	") {\n"
	"    result[index] = input[index] * scale;\n"
	"}\n"
	"kernel void nn_tensor_broadcast_scalar(\n"
	"    const device float *left [[buffer(0)]],\n"
	"    const device float *right [[buffer(1)]],\n"
	"    device float *result [[buffer(2)]],\n"
	"    constant NNMetalBroadcastParams &params [[buffer(3)]],\n"
	"    uint index [[thread_position_in_grid]]\n"
	") {\n"
	"    if (index >= params.count) {\n"
	"        return;\n"
	"    }\n"
	"    float a = (params.mode == 0u) ? left[index] : left[0];\n"
	"    float b = (params.mode == 1u) ? right[index] : right[0];\n"
	"    result[index] = nn_broadcast_apply(params.op, a, b);\n"
	"}\n"
	"kernel void nn_tensor_broadcast_last_axis(\n"
	"    const device float *left [[buffer(0)]],\n"
	"    const device float *right [[buffer(1)]],\n"
	"    device float *result [[buffer(2)]],\n"
	"    constant NNMetalBroadcastParams &params [[buffer(3)]],\n"
	"    uint2 gid [[thread_position_in_grid]]\n"
	") {\n"
	"    uint col = gid.x;\n"
	"    uint row = gid.y;\n"
	"    uint rows = params.dims[0];\n"
	"    uint cols = params.dims[1];\n"
	"    if (col >= cols || row >= rows) {\n"
	"        return;\n"
	"    }\n"
	"    ulong idx = ulong(row) * ulong(cols) + ulong(col);\n"
	"    float a = (params.mode == 0u) ? left[idx] : left[col];\n"
	"    float b = (params.mode == 0u) ? right[col] : right[idx];\n"
	"    result[idx] = nn_broadcast_apply(params.op, a, b);\n"
	"}\n"
	"kernel void nn_tensor_broadcast_general(\n"
	"    const device float *left [[buffer(0)]],\n"
	"    const device float *right [[buffer(1)]],\n"
	"    device float *result [[buffer(2)]],\n"
	"    constant NNMetalBroadcastParams &params [[buffer(3)]],\n"
	"    uint index [[thread_position_in_grid]]\n"
	") {\n"
	"    if (index >= params.count) {\n"
	"        return;\n"
	"    }\n"
	"    uint rem = index;\n"
	"    ulong leftIdx = 0;\n"
	"    ulong rightIdx = 0;\n"
	"    for (uint d = 0; d < params.rank; d++) {\n"
	"        uint stride = params.outStrides[d];\n"
	"        uint coord = rem / stride;\n"
	"        rem = rem - coord * stride;\n"
	"        leftIdx += ulong(coord) * ulong(params.leftStrides[d]);\n"
	"        rightIdx += ulong(coord) * ulong(params.rightStrides[d]);\n"
	"    }\n"
	"    result[index] = nn_broadcast_apply(params.op, left[leftIdx], right[rightIdx]);\n"
	"}\n";

#endif
