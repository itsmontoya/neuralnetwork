#ifndef NN_INTERNAL_DEVICE_TRANSPOSE_METAL_SOURCE_H
#define NN_INTERNAL_DEVICE_TRANSPOSE_METAL_SOURCE_H

// General contiguous tensor transpose kernels for 2-byte (Float16/BFloat16) and
// 4-byte (Float32) elements. Compiled lazily with fastMathEnabled = NO.
static const char *nnMetalTensorTransposeSource =
	"struct NNMetalTransposeParams {\n"
	"    uint rank;\n"
	"    uint count;\n"
	"    uint dims[6];\n"
	"    uint outStrides[6];\n"
	"    uint inStrides[6];\n"
	"};\n"
	"kernel void nn_tensor_transpose_2d_u32(\n"
	"    const device uint *input [[buffer(0)]],\n"
	"    device uint *result [[buffer(1)]],\n"
	"    constant NNMetalTransposeParams &params [[buffer(2)]],\n"
	"    uint2 tgid [[threadgroup_position_in_grid]],\n"
	"    uint2 tid [[thread_position_in_threadgroup]]\n"
	") {\n"
	"    threadgroup uint tile[16][17];\n"
	"    uint inCols = params.dims[0];\n"
	"    uint inRows = params.dims[1];\n"
	"    uint inCol = tgid.x * 16u + tid.x;\n"
	"    uint inRow = tgid.y * 16u + tid.y;\n"
	"    if (inCol < inCols && inRow < inRows) {\n"
	"        tile[tid.y][tid.x] = input[ulong(inRow) * ulong(inCols) + ulong(inCol)];\n"
	"    }\n"
	"    threadgroup_barrier(mem_flags::mem_threadgroup);\n"
	"    uint outCol = tgid.y * 16u + tid.x;\n"
	"    uint outRow = tgid.x * 16u + tid.y;\n"
	"    if (outCol < inRows && outRow < inCols) {\n"
	"        result[ulong(outRow) * ulong(inRows) + ulong(outCol)] = tile[tid.x][tid.y];\n"
	"    }\n"
	"}\n"
	"kernel void nn_tensor_transpose_2d_u16(\n"
	"    const device ushort *input [[buffer(0)]],\n"
	"    device ushort *result [[buffer(1)]],\n"
	"    constant NNMetalTransposeParams &params [[buffer(2)]],\n"
	"    uint2 tgid [[threadgroup_position_in_grid]],\n"
	"    uint2 tid [[thread_position_in_threadgroup]]\n"
	") {\n"
	"    threadgroup ushort tile[16][17];\n"
	"    uint inCols = params.dims[0];\n"
	"    uint inRows = params.dims[1];\n"
	"    uint inCol = tgid.x * 16u + tid.x;\n"
	"    uint inRow = tgid.y * 16u + tid.y;\n"
	"    if (inCol < inCols && inRow < inRows) {\n"
	"        tile[tid.y][tid.x] = input[ulong(inRow) * ulong(inCols) + ulong(inCol)];\n"
	"    }\n"
	"    threadgroup_barrier(mem_flags::mem_threadgroup);\n"
	"    uint outCol = tgid.y * 16u + tid.x;\n"
	"    uint outRow = tgid.x * 16u + tid.y;\n"
	"    if (outCol < inRows && outRow < inCols) {\n"
	"        result[ulong(outRow) * ulong(inRows) + ulong(outCol)] = tile[tid.x][tid.y];\n"
	"    }\n"
	"}\n"
	"kernel void nn_tensor_transpose_general_u32(\n"
	"    const device uint *input [[buffer(0)]],\n"
	"    device uint *result [[buffer(1)]],\n"
	"    constant NNMetalTransposeParams &params [[buffer(2)]],\n"
	"    uint index [[thread_position_in_grid]]\n"
	") {\n"
	"    if (index >= params.count) {\n"
	"        return;\n"
	"    }\n"
	"    uint rem = index;\n"
	"    ulong inIdx = 0;\n"
	"    for (uint d = 0u; d < params.rank; d++) {\n"
	"        uint stride = params.outStrides[d];\n"
	"        uint coord = rem / stride;\n"
	"        rem = rem - coord * stride;\n"
	"        inIdx += ulong(coord) * ulong(params.inStrides[d]);\n"
	"    }\n"
	"    result[index] = input[inIdx];\n"
	"}\n"
	"kernel void nn_tensor_transpose_general_u16(\n"
	"    const device ushort *input [[buffer(0)]],\n"
	"    device ushort *result [[buffer(1)]],\n"
	"    constant NNMetalTransposeParams &params [[buffer(2)]],\n"
	"    uint index [[thread_position_in_grid]]\n"
	") {\n"
	"    if (index >= params.count) {\n"
	"        return;\n"
	"    }\n"
	"    uint rem = index;\n"
	"    ulong inIdx = 0;\n"
	"    for (uint d = 0u; d < params.rank; d++) {\n"
	"        uint stride = params.outStrides[d];\n"
	"        uint coord = rem / stride;\n"
	"        rem = rem - coord * stride;\n"
	"        inIdx += ulong(coord) * ulong(params.inStrides[d]);\n"
	"    }\n"
	"    result[index] = input[inIdx];\n"
	"}\n";

#endif
